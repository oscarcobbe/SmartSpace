#!/usr/bin/env node
/**
 * Smart Space's LinkedIn posts for the CRM's Outreach page, built from the
 * packaged folder rather than retyped, as build-linkedin-posts.mjs does for
 * SmartCare Living: each numbered folder holds caption.txt, still.jpg and
 * film.mp4, and the launch post has a long film in its own folder.
 *
 * Writes src/lib/crm/content/smartspace-linkedin-posts.ts and copies the
 * media to public/outreach/linkedin/smartspace/. With --check, fails if the
 * committed file and the folder disagree. Without the folder (Vercel), the
 * committed file stands.
 *
 *   node scripts/build-smartspace-linkedin.mjs [--check]
 */
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync, copyFileSync, statSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const PACKAGE = resolve(ROOT, "..", "..", "Smart Space LinkedIn", "2026-10-12 Services");
const OUT = join(ROOT, "src/lib/crm/content/smartspace-linkedin-posts.ts");
const PUBLIC = join(ROOT, "public/outreach/linkedin/smartspace");
const CHECK = process.argv.includes("--check");

if (!existsSync(PACKAGE)) {
  console.log(`No Smart Space LinkedIn package at ${PACKAGE}. Nothing regenerated; the committed file stands.`);
  process.exit(0);
}

function post(dir, n, title) {
  const raw = readFileSync(join(dir, "caption.txt"), "utf8").trim();
  const lines = raw.split("\n");
  /* The last line of hashtags becomes the tags, so the caption reads without them and Copy puts them back. */
  const tagLine = /^(#\w+\s*)+$/.test(lines.at(-1).trim()) ? lines.pop().trim() : "";
  const caption = lines.join("\n").trim();
  const slug = n.toLowerCase().replace(/[^a-z0-9]+/g, "-");
  return {
    n,
    title,
    hook: caption.split("\n")[0],
    caption,
    tags: tagLine ? tagLine.split(/\s+/) : [],
    video: `/outreach/linkedin/smartspace/${slug}.mp4`,
    still: `/outreach/linkedin/smartspace/${slug}.jpg`,
    close: "",
    _src: dir,
  };
}

const posts = [];
for (const name of readdirSync(PACKAGE).filter((f) => /^\d\d /.test(f)).sort()) {
  const n = name.slice(0, 2);
  const title = name.slice(3).replace(/^LAUNCH /, "Launch: ");
  posts.push(post(join(PACKAGE, name), n, title));
  const long = readdirSync(join(PACKAGE, name)).find((f) => /^Long film/.test(f));
  if (long) posts.push(post(join(PACKAGE, name, long), `${n}b`, `${title}, ${long.replace("Long film", "the long film")}`));
}

const body = `/**
 * Generated by scripts/build-smartspace-linkedin.mjs. Do not edit.
 *
 * Source: Smart Space LinkedIn/2026-10-12 Services (caption.txt, still.jpg, film.mp4 per post)
 * Assets: public/outreach/linkedin/smartspace/
 */
import type { LinkedInPost } from "./linkedin-posts";

export const SMARTSPACE_LINKEDIN_POSTS: LinkedInPost[] = ${JSON.stringify(posts.map(({ _src, ...p }) => p), null, 2)};
`;

if (CHECK) {
  const ok = existsSync(OUT) && readFileSync(OUT, "utf8") === body;
  const missing = posts.flatMap((p) => [p.video, p.still]).filter((f) => !existsSync(join(ROOT, "public", f)));
  if (!ok || missing.length) {
    console.error(`smartspace-linkedin: ${!ok ? "the generated file is out of date" : ""}${missing.length ? ` ${missing.length} media file(s) missing` : ""}. Run node scripts/build-smartspace-linkedin.mjs.`);
    process.exit(1);
  }
  console.log(`smartspace-linkedin: ${posts.length} posts match the package.`);
  process.exit(0);
}

mkdirSync(PUBLIC, { recursive: true });
for (const p of posts) {
  for (const [src, dest] of [["film.mp4", p.video], ["still.jpg", p.still]]) {
    const from = join(p._src, src), to = join(ROOT, "public", dest);
    if (!existsSync(to) || statSync(to).size !== statSync(from).size) copyFileSync(from, to);
  }
}
writeFileSync(OUT, body);
console.log(`smartspace-linkedin: ${posts.length} posts written, media in public/outreach/linkedin/smartspace/`);
